/**
 * Universal dispatcher for both Encrypted PDF and Encrypted Excel downloads
 */
export async function generateSecureReport(
  options: DocumentExportOptions & { format: 'PDF' | 'XLSX' }
): Promise<{ filename: string; size: number }> {
  if (options.format === 'XLSX') {
    return generateEncryptedExcelReport(options);
  }
  return generateEncryptedPdfReport(options);
}
