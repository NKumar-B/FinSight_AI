import { jsPDF } from 'jspdf';
import XlsxPopulate from 'xlsx-populate/browser/xlsx-populate.js';

export interface DocumentExportOptions {
  reportId: string;
  reportName: string;
  format?: 'PDF' | 'XLSX';
  password?: string;
  classification?: string;
  generatedBy?: string;
}

